"""API reference page generator: the route table of `docs/src/api.md`.

`asteroidea_ingest.routes.ROUTES` is the one list of API routes. This module writes the
method, path, group, function and summary of each route between two marker comments in
`docs/src/api.md`, and checks that the page is current: the table matches the route
table, every route has a hand-written section, and no section names an unknown route.
Run it with `make api-docs`. It imports no `aws_cdk`.
"""

import re
import sys
from pathlib import Path
from typing import Final

from asteroidea_ingest import routes

REPO_ROOT: Final = Path(__file__).resolve().parents[3]
PAGE: Final = REPO_ROOT / "docs" / "src" / "api.md"
BEGIN: Final = "<!-- routes:begin (generated by make api-docs; do not edit) -->"
END: Final = "<!-- routes:end -->"
STALE: Final = "docs/src/api.md is stale: run make api-docs"
# A section heading is "### `GET /sessions/{id}`".
SECTION_RE: Final = re.compile(r"^### `([A-Z]+ \S+)`\s*$", re.MULTILINE)


def render_table() -> str:
    """Return the Markdown table of the current route table, one row per route."""
    lines = [
        "| Method | Path | Group | Function | Summary |",
        "|---|---|---|---|---|",
    ]
    lines += [
        f"| {r.method} | `{r.path}` | {r.group} | {r.function} | {r.summary} |"
        for r in routes.ROUTES
    ]
    return "\n".join(lines)


def _span(text: str) -> tuple[int, int]:
    """Return the offsets of the text between the markers; ValueError when absent."""
    begin, end = text.find(BEGIN), text.find(END)
    if begin < 0 or end < begin:
        msg = f"docs/src/api.md needs the markers {BEGIN!r} and {END!r}"
        raise ValueError(msg)
    return begin + len(BEGIN), end


def render_page(text: str) -> str:
    """Return `text` with the text between the markers replaced by the current table."""
    start, end = _span(text)
    return f"{text[:start]}\n\n{render_table()}\n\n{text[end:]}"


def section_keys(text: str) -> list[str]:
    """Return the route key of each section heading, in page order."""
    return [str(key) for key in SECTION_RE.findall(text)]


def problems(text: str) -> list[str]:
    """Return every way `text` disagrees with the route table; empty when current."""
    found: list[str] = []
    try:
        if render_page(text) != text:
            found.append(STALE)
    except ValueError as err:
        found.append(str(err))
    keys = [r.key for r in routes.ROUTES]
    sections = section_keys(text)
    found += [f"missing section for {k}" for k in keys if k not in sections]
    found += [
        f"section for a route not in the table: {k}" for k in sections if k not in keys
    ]
    found += [
        f"duplicate section for {k}"
        for k in sorted({s for s in sections if sections.count(s) > 1})
    ]
    return found


def main() -> int:
    """Rewrite the table in `docs/src/api.md`; exit 1 when the markers are missing."""
    text = PAGE.read_text(encoding="utf-8")
    try:
        PAGE.write_text(render_page(text), encoding="utf-8")
    except ValueError as err:
        sys.stderr.write(f"{err}\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
